import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
let plays = 0, pauses = 0, cleanup;
const media = { src: '', paused: true, ended: false, play() { plays++; this.paused = false; return Promise.resolve(); }, pause() { pauses++; this.paused = true; } };
const fakeReact = { useRef: (v) => ({ current: v === null ? media : v }), useState: (v) => [v, () => {}], useEffect: (f) => { cleanup = f(); } };
const source = fs.readFileSync('src/ContinuousAudio.tsx','utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText;
const out = { exports: {} };
new Function('require','module','exports',js)((id) => id === 'react' ? fakeReact : id.endsWith('.css') ? {} : require(id), out, out.exports);
const tree = out.exports.default({ urls: ['one.mp3','two.mp3','three.mp3'], rtl: true });
const children = tree.props.children;
const audio = children.find(x => x?.type === 'audio');
const button = children.find(x => x?.type === 'button');
assert.equal(plays,0,'mount does not autoplay');
assert.equal(media.src,'one.mp3');
button.props.onClick(); assert.equal(plays,1);
audio.props.onEnded(); assert.equal(media.src,'two.mp3'); assert.equal(plays,2);
audio.props.onEnded(); assert.equal(media.src,'three.mp3'); assert.equal(plays,3);
audio.props.onEnded(); assert.equal(plays,3,'last part stops without looping');
media.paused=true;media.ended=true;button.props.onClick();assert.equal(media.src,'one.mp3','explicit replay restarts playlist');
button.props.onClick();assert.equal(media.paused,true,'pause is supported');
cleanup();assert.ok(pauses>0,'unmount stops playback');
assert.ok(!source.includes('invokeBookAI'),'saved audio player cannot generate paid audio');
console.log('Continuous audio: ordered transitions, final stop, replay, pause, cleanup, no generation passed.');
